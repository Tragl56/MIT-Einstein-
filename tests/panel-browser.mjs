// Start the isolated demo on PANEL_TEST_URL (default :5187) before running this check.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '../patient-app/node_modules/playwright/index.mjs';

const base = process.env.PANEL_TEST_URL || 'http://localhost:5187';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let pairingPosts = 0;
let documentPosts = 0;
page.on('request', request => {
  if (request.method() === 'POST' && request.url().endsWith('/mobile-pairing')) pairingPosts++;
  if (request.method() === 'POST' && request.url().endsWith('/documents')) documentPosts++;
});
const headers = { 'x-demo-usuario': 'usr-carla' };
const read = async () => {
  const response = await page.request.get(`${base}/api/pro/pacientes/pac-maria/mobile-data`, { headers });
  assert.equal(response.status(), 200);
  return response.json();
};

try {
  await mkdir('test-results/panel', { recursive: true });
  // The demo language is shared and starts in Portuguese; switching restarts the fictional data.
  await page.request.post(`${base}/api/demo/idioma`, { data: { idioma: 'pt-BR' } });
  await page.goto(base);
  await page.locator('#btn-entrar-usr-carla').waitFor();
  await page.screenshot({ path: 'test-results/panel/login-desktop.png' });
  await page.locator('#btn-entrar-usr-carla').click();
  await page.getByRole('tab', { name: 'Aplicativo do paciente' }).click();
  const panel = page.getByTestId('mobile-integration');
  await panel.getByRole('heading', { name: 'Agenda publicada' }).waitFor();
  assert.equal(await page.locator('body').evaluate(el => getComputedStyle(el).fontFamily.includes('Manrope')), true);
  await page.getByTestId('generate-pairing').evaluate(button => { button.click(); button.click(); });
  await page.getByTestId('pairing-code').waitFor();
  assert.equal(pairingPosts, 1, 'two immediate clicks issue one pairing mutation');
  assert.match(await page.getByTestId('pairing-code').innerText(), /^[A-Z0-9-]+$/);
  const appointment = panel.getByRole('region', { name: 'Agenda publicada' }).locator('form').first();
  const before = await read();
  const appointmentTitle = `Consulta compartilhada ${Date.now()}`;
  await appointment.getByLabel('Título', { exact: true }).fill(appointmentTitle);
  await appointment.getByLabel('Local', { exact: true }).fill('Unidade fictícia · Sala 2');
  await appointment.getByLabel('Preparo autorizado').fill('Leve os documentos autorizados pela equipe.');
  await appointment.getByRole('button', { name: 'Salvar e atualizar no aplicativo' }).click();
  await panel.getByRole('status').filter({ hasText: 'Compromisso salvo' }).waitFor();
  const updated = await read();
  assert.equal(updated.appointments[0].title, appointmentTitle);
  assert.equal(updated.appointments[0].preparation, 'Leve os documentos autorizados pela equipe.');
  assert.equal(updated.appointments[0].id, before.appointments[0].id);
  const journey = panel.getByRole('region', { name: 'Jornada compartilhada' }).locator('form').first();
  const journeyTitle = `Etapa revisada ${Date.now()}`;
  await journey.getByLabel('Título', { exact: true }).fill(journeyTitle);
  await journey.getByLabel('Estado', { exact: true }).selectOption('completed');
  await journey.getByRole('button', { name: 'Publicar alteração da jornada' }).click();
  await panel.getByRole('status').filter({ hasText: 'Jornada salva' }).waitFor();
  assert.equal((await read()).journey[0].title, journeyTitle);
  assert.equal((await read()).journey[0].status, 'completed');
  const document = page.getByTestId('publish-document');
  const documentTitle = `Orientação revisada ${Date.now()}`;
  await document.getByLabel('Título', { exact: true }).fill(documentTitle);
  await document.getByLabel('Texto autorizado').fill('Conteúdo fictício revisado pela equipe para publicação.');
  await document.getByRole('button', { name: 'Aprovar e publicar documento' }).click();
  assert.equal(documentPosts, 0, 'document cannot publish without the explicit approval checkbox');
  await document.getByRole('checkbox').check();
  await document.getByRole('button', { name: 'Aprovar e publicar documento' }).click();
  await panel.getByRole('status').filter({ hasText: 'Documento publicado' }).waitFor();
  assert.equal(documentPosts, 1);
  const released = (await read()).documents.filter(item => item.title === documentTitle);
  assert.equal(released.length, 1);
  assert.equal(released[0].published, true);
  assert.deepEqual(released[0].body, ['Conteúdo fictício revisado pela equipe para publicação.']);
  await page.route('**/api/pro/pacientes/pac-maria/documents', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ mensagem: 'Falha de teste: publicação não recebida.' }) }));
  await document.getByLabel('Título', { exact: true }).fill('Rascunho preservado após falha');
  await document.getByLabel('Texto autorizado').fill('Este texto não foi publicado.');
  await document.getByRole('checkbox').check();
  await document.getByRole('button', { name: 'Aprovar e publicar documento' }).click();
  await panel.getByRole('alert').filter({ hasText: 'publicação não recebida' }).waitFor();
  assert.equal(await document.getByLabel('Título', { exact: true }).inputValue(), 'Rascunho preservado após falha');
  assert.equal((await read()).documents.some(item => item.title === 'Rascunho preservado após falha'), false);
  await page.unroute('**/api/pro/pacientes/pac-maria/documents');
  await panel.getByRole('button', { name: 'Atualizar dados', exact: true }).click();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/panel/connected-desktop.png' });
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Menu do usuário' }).click();
  await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'English' }).click()]);
  await page.getByRole('tab', { name: 'Patient app' }).click();
  await panel.getByRole('heading', { name: 'Patient app', exact: true }).waitFor();
  await panel.getByRole('region', { name: 'Published schedule' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => scrollTo(0, 0));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'mobile layout does not overflow horizontally');
  await panel.locator('#mobile-pairing-title').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/panel/connected-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS: real pairing, double-click guard, appointment/preparation, journey, explicit document approval, PT/EN, desktop/mobile, zero page errors.');
} finally {
  await page.request.post(`${base}/api/demo/idioma`, { data: { idioma: 'pt-BR' } }).catch(() => {});
  await browser.close();
}
